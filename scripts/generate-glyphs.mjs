import { readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import process from "node:process"

import { parse } from "node-html-parser"

const root = process.cwd()
const iconsDirectory = path.join(root, "src/glyphs/icons")
const outputFile = path.join(root, "src/glyphs/definitions.ts")
const check = process.argv.includes("--check")

const supportedTags = new Set(["circle", "line", "path", "polyline", "rect"])
const ignoredTags = new Set(["desc", "metadata", "title"])
const rootAttributes = new Set([
  "fill",
  "stroke",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-miterlimit",
  "stroke-width",
  "vector-effect",
  "viewBox"
])
const shapeAttributes = new Set([
  "clip-rule",
  "cx",
  "cy",
  "d",
  "fill",
  "fill-opacity",
  "fill-rule",
  "height",
  "opacity",
  "points",
  "r",
  "rx",
  "ry",
  "stroke",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-miterlimit",
  "stroke-opacity",
  "stroke-width",
  "vector-effect",
  "width",
  "x",
  "x1",
  "x2",
  "y",
  "y1",
  "y2"
])
const inheritedAttributes = new Set([
  "fill",
  "fill-opacity",
  "fill-rule",
  "opacity",
  "stroke",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-miterlimit",
  "stroke-opacity",
  "stroke-width",
  "vector-effect"
])

const nameForFile = (filename) => {
  const name = path.basename(filename, ".svg").replace(/[-_]+(.)?/g, (_, next) =>
    next ? next.toUpperCase() : ""
  )
  if (!/^[a-z][A-Za-z0-9]*$/.test(name)) {
    throw new Error(`${filename}: filenames must produce a camel-case glyph name`)
  }
  return name
}

const numberOrString = (value) => {
  const number = Number(value)
  return value.trim() !== "" && Number.isFinite(number) ? number : value
}

const attributesFor = (element, allowed, filename) => {
  const attributes = {}
  for (const [name, value] of Object.entries(element.attributes)) {
    if (name === "xmlns") continue
    if (!allowed.has(name)) {
      throw new Error(`${filename}: unsupported ${element.tagName.toLowerCase()} attribute ${name}`)
    }
    attributes[name] = numberOrString(value)
  }
  return attributes
}

const childNodes = (parent, inherited, filename) => {
  const nodes = []
  for (const child of parent.childNodes) {
    if (child.nodeType === 3) {
      if (child.rawText.trim() !== "") {
        throw new Error(`${filename}: unexpected text inside SVG`)
      }
      continue
    }
    if (child.nodeType !== 1) continue
    const tag = child.tagName.toLowerCase()
    if (ignoredTags.has(tag)) continue
    if (tag === "g") {
      const groupAttributes = attributesFor(child, inheritedAttributes, filename)
      nodes.push(...childNodes(child, { ...inherited, ...groupAttributes }, filename))
      continue
    }
    if (!supportedTags.has(tag)) {
      throw new Error(`${filename}: unsupported SVG element <${tag}>`)
    }
    nodes.push({
      tag,
      attrs: {
        ...inherited,
        ...attributesFor(child, shapeAttributes, filename)
      }
    })
  }
  return nodes
}

const entries = []
const names = new Map()
for (const filename of (await readdir(iconsDirectory)).filter((file) => file.endsWith(".svg")).sort()) {
  const name = nameForFile(filename)
  const collision = names.get(name)
  if (collision !== undefined) {
    throw new Error(`${filename}: glyph name ${name} already belongs to ${collision}`)
  }
  names.set(name, filename)
  const source = await readFile(path.join(iconsDirectory, filename), "utf8")
  const document = parse(source, { lowerCaseTagName: false })
  const svg = document.querySelector("svg")
  if (svg === null || document.querySelectorAll("svg").length !== 1) {
    throw new Error(`${filename}: expected exactly one <svg> root`)
  }
  const rootAttrs = attributesFor(svg, rootAttributes, filename)
  const viewBox = rootAttrs.viewBox
  if (typeof viewBox !== "string" || viewBox.trim() === "") {
    throw new Error(`${filename}: <svg> requires a viewBox`)
  }
  delete rootAttrs.viewBox
  const nodes = childNodes(svg, {}, filename)
  if (nodes.length === 0) throw new Error(`${filename}: glyph has no supported shapes`)
  entries.push({ name, definition: { viewBox, attrs: rootAttrs, nodes } })
}

const namesSource = entries.map(({ name }) => `  ${JSON.stringify(name)}`).join(",\n")
const definitionsSource = entries.map(({ name, definition }) =>
  `  ${JSON.stringify(name)}: ${JSON.stringify(definition)}`
).join(",\n")
const generated = `// Generated by scripts/generate-glyphs.mjs. Do not edit.\nimport type { GlyphDefinition } from "./types.js"\n\nexport const glyphNames = [\n${namesSource}\n] as const\n\nexport type GlyphName = (typeof glyphNames)[number]\n\nexport const glyphDefinitions = {\n${definitionsSource}\n} as const satisfies Record<GlyphName, GlyphDefinition>\n`

if (check) {
  const current = await readFile(outputFile, "utf8").catch(() => "")
  if (current !== generated) {
    throw new Error("Generated glyph definitions are stale; run npm run generate:glyphs")
  }
} else {
  await writeFile(outputFile, generated)
}
